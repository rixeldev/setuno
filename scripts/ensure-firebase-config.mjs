// Generates db/firebaseConfig.ts from environment variables when the file is
// not present (or when it was generated for a *different* environment).
// The real config stays out of git, so local development keeps its own copy
// (this script is a no-op there) while CI — Vercel — provides the values as
// environment variables and gets the file written before the build.
//
// Staging (roadmap #80 / P0.7): `APP_ENV=staging` selects the FIREBASE_STAGING_*
// names instead, so a staging build can never mix a staging key with a prod
// project id. Values come from the EAS `preview` environment on cloud builds
// and from the gitignored .env.staging locally (loaded below; real process
// env always wins). The generated file carries `firebaseEnvironment` as its
// stamp: a mismatch against the requested environment regenerates it — after
// backing the previous file up to db/firebaseConfig.ts.bak — but only once
// the new environment's variables all validate, so a half-set flip never
// destroys the working config.
//
// Production names, required when the file is missing:
//   FIREBASE_API_KEY, FIREBASE_AUTH_DOMAIN, FIREBASE_PROJECT_ID,
//   FIREBASE_STORAGE_BUCKET, FIREBASE_MESSAGING_SENDER_ID, FIREBASE_APP_ID
// Staging names: the same list with a FIREBASE_STAGING_ prefix.
// Optional (both environments): _DATABASE_URL, _MEASUREMENT_ID suffixes, plus
//   APP_VERSION_ID, ADMOB_BANNER_ID, ADMOB_INTERSTITIAL_ID.
import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const target = join(root, "db", "firebaseConfig.ts")

// dotenv-style loading for local runs: .env, .env.local, then .env.<APP_ENV>.
// Existing process env wins over every file (CI/EAS values are real env).
const loadEnvFile = (path) => {
  if (!existsSync(path)) return
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line)
    if (!match || line.trim().startsWith("#")) continue
    const [, key, raw] = match
    if (process.env[key] === undefined) {
      process.env[key] = raw.replace(/^["']|["']$/g, "")
    }
  }
}
loadEnvFile(join(root, ".env"))
loadEnvFile(join(root, ".env.local"))

const environment = process.env.APP_ENV === "staging" ? "staging" : "production"
if (environment === "staging") loadEnvFile(join(root, ".env.staging"))

const prefix = environment === "staging" ? "FIREBASE_STAGING_" : "FIREBASE_"

const required = [
  "API_KEY",
  "AUTH_DOMAIN",
  "PROJECT_ID",
  "STORAGE_BUCKET",
  "MESSAGING_SENDER_ID",
  "APP_ID",
].map((name) => prefix + name)

const fileStamp = (path) => {
  if (!existsSync(path)) return null
  const match = /export const firebaseEnvironment = "([^"]+)"/.exec(readFileSync(path, "utf8"))
  // A hand-written file predates the stamp; it is the local production one.
  return match?.[1] ?? "production"
}

const desired = environment
const current = fileStamp(target)

if (current === desired) {
  console.log(`[firebase-config] using the existing db/firebaseConfig.ts (${desired})`)
  process.exit(0)
}

const env = (name) => process.env[name] ?? ""

const missing = required.filter((name) => env(name).length === 0)
if (missing.length > 0) {
  console.error(
    `[firebase-config] db/firebaseConfig.ts holds the "${current}" config and the "${desired}" ` +
      "environment variables are not set, so it was left untouched:\n  " +
      missing.join("\n  "),
  )
  process.exit(1)
}

if (current !== null) {
  renameSync(target, `${target}.bak`)
  console.log(`[firebase-config] backed the ${current} config up to db/firebaseConfig.ts.bak`)
}

const file = `// Generated by scripts/ensure-firebase-config.mjs for the CI/web build.
import { getApp, getApps, initializeApp } from "@react-native-firebase/app"
import { getReactNativePersistence } from "firebase/auth"
import { getStorage } from "@react-native-firebase/storage"
import { initializeAuth } from "@react-native-firebase/auth"
import ReactNativeAsyncStorage from "@react-native-async-storage/async-storage"

export const firebaseEnvironment = "${desired}"

export const appVersionId = "${env("APP_VERSION_ID")}"
export const adBannerId = "${env("ADMOB_BANNER_ID")}"
export const adInterstitialId = "${env("ADMOB_INTERSTITIAL_ID")}"

export const firebaseConfig = {
  apiKey: "${env(prefix + "API_KEY")}",
  authDomain: "${env(prefix + "AUTH_DOMAIN")}",
  databaseURL: "${env(prefix + "DATABASE_URL")}",
  projectId: "${env(prefix + "PROJECT_ID")}",
  storageBucket: "${env(prefix + "STORAGE_BUCKET")}",
  messagingSenderId: "${env(prefix + "MESSAGING_SENDER_ID")}",
  appId: "${env(prefix + "APP_ID")}",
  measurementId: "${env(prefix + "MEASUREMENT_ID")}",
}

const app = getApps().length === 0 ? initializeApp(firebaseConfig) : getApp()
const auth = initializeAuth(getApp(), {
  persistence: getReactNativePersistence(ReactNativeAsyncStorage),
})
const storage = getStorage(getApp())

export { app, auth, storage }
`

writeFileSync(target, file)
console.log(`[firebase-config] wrote db/firebaseConfig.ts from the ${desired} environment variables`)
