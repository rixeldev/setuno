// Generates db/firebaseConfig.ts from environment variables when the file is
// not present. The real config stays out of git, so local development keeps its
// own copy (this script is a no-op there) while CI — Vercel — provides the
// values as environment variables and gets the file written before the build.
//
// Required when the file is missing:
//   FIREBASE_API_KEY, FIREBASE_AUTH_DOMAIN, FIREBASE_PROJECT_ID,
//   FIREBASE_STORAGE_BUCKET, FIREBASE_MESSAGING_SENDER_ID, FIREBASE_APP_ID
// Optional: FIREBASE_DATABASE_URL, FIREBASE_MEASUREMENT_ID, APP_VERSION_ID,
//   ADMOB_BANNER_ID, ADMOB_INTERSTITIAL_ID.
import { existsSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const target = join(root, "db", "firebaseConfig.ts")

if (existsSync(target)) {
  console.log("[firebase-config] using the existing db/firebaseConfig.ts")
  process.exit(0)
}

const env = (name) => process.env[name] ?? ""

const required = [
  "FIREBASE_API_KEY",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_STORAGE_BUCKET",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_APP_ID",
]
const missing = required.filter((name) => env(name).length === 0)
if (missing.length > 0) {
  console.error(
    "[firebase-config] db/firebaseConfig.ts is missing and these environment variables are not set:\n  " +
      missing.join("\n  "),
  )
  process.exit(1)
}

const file = `// Generated by scripts/ensure-firebase-config.mjs for the CI/web build.
import { getApp, getApps, initializeApp } from "@react-native-firebase/app"
import { getReactNativePersistence } from "firebase/auth"
import { getStorage } from "@react-native-firebase/storage"
import { initializeAuth } from "@react-native-firebase/auth"
import ReactNativeAsyncStorage from "@react-native-async-storage/async-storage"

export const appVersionId = "${env("APP_VERSION_ID")}"
export const adBannerId = "${env("ADMOB_BANNER_ID")}"
export const adInterstitialId = "${env("ADMOB_INTERSTITIAL_ID")}"

export const firebaseConfig = {
  apiKey: "${env("FIREBASE_API_KEY")}",
  authDomain: "${env("FIREBASE_AUTH_DOMAIN")}",
  databaseURL: "${env("FIREBASE_DATABASE_URL")}",
  projectId: "${env("FIREBASE_PROJECT_ID")}",
  storageBucket: "${env("FIREBASE_STORAGE_BUCKET")}",
  messagingSenderId: "${env("FIREBASE_MESSAGING_SENDER_ID")}",
  appId: "${env("FIREBASE_APP_ID")}",
  measurementId: "${env("FIREBASE_MEASUREMENT_ID")}",
}

const app = getApps().length === 0 ? initializeApp(firebaseConfig) : getApp()
const auth = initializeAuth(getApp(), {
  persistence: getReactNativePersistence(ReactNativeAsyncStorage),
})
const storage = getStorage(getApp())

export { app, auth, storage }
`

writeFileSync(target, file)
console.log("[firebase-config] wrote db/firebaseConfig.ts from environment variables")
