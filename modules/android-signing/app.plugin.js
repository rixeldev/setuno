const { withAppBuildGradle } = require("expo/config-plugins")

/**
 * Firma de release con `keystore.properties` (raíz del repo, gitignored).
 *
 * El template de Expo firma el release con la keystore de **debug**, así que un
 * `bundleRelease` produce un AAB que Play rechaza (o, peor, que se sube con la
 * clave equivocada). Este plugin añade al `android/app/build.gradle` generado
 * una configuración `release` que lee las credenciales **en tiempo de build**
 * desde `keystore.properties`:
 *
 *   - Las contraseñas NO se copian al `build.gradle` (que también es generado):
 *     solo se inyecta el código que lee el fichero.
 *   - Sobrevive a `expo prebuild` con y sin `--clean`, porque `android/` se
 *     regenera a partir de esta config.
 *   - Si `keystore.properties` no existe (p. ej. en EAS, donde la firma la
 *     inyecta la nube) no toca nada y solo avisa por consola.
 *
 * Formato del fichero (raíz del repo):
 *
 *   storeFile=/ruta/absoluta/o/relativa/androidStudioKey.jks
 *   storePassword=...
 *   keyAlias=...
 *   keyPassword=...
 *
 * La ruta relativa se resuelve contra la raíz del repo, no contra `android/app`.
 */

const MARKER = "// @generated by modules/android-signing"

const SIGNING_BLOCK = `
${MARKER} (config plugin: no editar a mano; se regenera en cada prebuild).
// Release firmado con la keystore del proyecto. El fichero está en la raíz del
// repo y está gitignored: las contraseñas nunca se escriben aquí.
def stopTriviaKeystore = rootProject.file("../keystore.properties")
if (stopTriviaKeystore.exists()) {
    def stopTriviaSigning = new Properties()
    stopTriviaKeystore.withInputStream { stopTriviaSigning.load(it) }

    def stopTriviaStorePath = stopTriviaSigning.getProperty("storeFile")
    def stopTriviaStoreFile = new File(stopTriviaStorePath)
    if (!stopTriviaStoreFile.isAbsolute()) {
        stopTriviaStoreFile = new File(stopTriviaKeystore.parentFile, stopTriviaStorePath)
    }

    android {
        signingConfigs {
            release {
                storeFile stopTriviaStoreFile
                storePassword stopTriviaSigning.getProperty("storePassword")
                keyAlias stopTriviaSigning.getProperty("keyAlias")
                keyPassword stopTriviaSigning.getProperty("keyPassword")
            }
        }
        buildTypes {
            release {
                signingConfig signingConfigs.release
            }
        }
    }
} else {
    logger.warn("")
    logger.warn("======================================================================")
    logger.warn("  keystore.properties NO encontrado en la raiz del proyecto.")
    logger.warn("  El release se firmara con la clave de DEBUG y Play lo rechazara.")
    logger.warn("  Crea el fichero (esta gitignored) o exporta las credenciales de EAS.")
    logger.warn("======================================================================")
    logger.warn("")
}
`

module.exports = function withAndroidSigning(config) {
  return withAppBuildGradle(config, (configWithMods) => {
    const gradle = configWithMods.modResults
    if (gradle.language !== "groovy") return configWithMods
    if (gradle.contents.includes(MARKER)) return configWithMods
    gradle.contents = `${gradle.contents.trimEnd()}\n${SIGNING_BLOCK}`
    return configWithMods
  })
}
